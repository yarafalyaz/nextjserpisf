export const dynamic = "force-dynamic"

import { renderEmployeeLoansPage } from "../../page"
import { statusLabel, indoToStatus } from "@/lib/utils/status-labels"
import type { Metadata } from "next"

export async function generateMetadata({
  params,
}: {
  params: Promise<{ status: string }>
}): Promise<Metadata> {
  const { status } = await params
  const dbStatus = indoToStatus[status] || status
  return {
    title: `Pinjaman Karyawan - ${statusLabel(dbStatus)}`,
  }
}

export default async function EmployeeLoanStatusPage({
  params,
  searchParams,
}: {
  params: Promise<{ status: string }>
  searchParams: Promise<{
    cari?: string
    halaman?: string
    pageSize?: string
  }>
}) {
  const { status } = await params
  return renderEmployeeLoansPage({
    statusParam: status,
    searchParams,
  })
}
