import { generateDocumentNumber } from "@/lib/utils/document-number"
import { nextSlug } from "@/lib/utils/slug-db"
import { safeAdd } from "@/lib/utils/math"
import { isRecurrenceFrequency, isWithinSchedule, nextRunAfter, type RecurrenceFrequency } from "@/lib/reports/recurring-schedule"
import { assertAccountsExist } from "@/lib/hooks/accounting.hook"
import { assertPeriodOpen } from "@/lib/services/period-lock.service"

export interface RecurringTemplate {
  accountId?: number | null
  paidFromAccountId?: number | null
  categoryId?: number | null
  vendorId?: number | null
  amount?: number
  description?: string
  lines?: { accountId: number; debit: number; credit: number; memo?: string }[]
}

export function parseRecurringTemplate(raw: string | null): RecurringTemplate {
  if (!raw) return {}
  try {
    const parsed = JSON.parse(raw)
    return parsed && typeof parsed === "object" ? (parsed as RecurringTemplate) : {}
  } catch {
    return {}
  }
}

/**
 * Reference key for a journal generated by a recurring schedule.
 *
 * `journals` is unique on (referenceType, referenceId), so a single schedule MUST get
 * a distinct key per occurrence — otherwise the 2nd run trips the constraint. Same
 * pattern as `ASSET_DEPRECIATION_YYYYMM` in the depreciation cron: the document date
 * lives in `referenceType`, while `referenceId` stays the real back-reference to the
 * source document (`recurringTransaction.id`). Before this, recurring journals were
 * written with a NULL reference, so nothing could be traced back to its schedule.
 */
export function recurringJournalReference(
  scheduleId: number,
  date: Date,
): { referenceType: string; referenceId: number } {
  const day = `${date.getFullYear()}${String(date.getMonth() + 1).padStart(2, "0")}${String(date.getDate()).padStart(2, "0")}`
  return { referenceType: `RecurringTransaction_${day}`, referenceId: scheduleId }
}

/**
 * Effective journal lines (account filled, amount > 0) plus the per-side totals.
 * Shared by the cron path and the "run now" action so both stop hand-rolling the
 * filter/total arithmetic separately.
 */
export function recurringJournalLines(template: RecurringTemplate) {
  const lines = (template.lines ?? []).filter((line) => line.accountId && (line.debit > 0 || line.credit > 0))
  return {
    lines,
    totalDebit: lines.reduce((sum, line) => safeAdd(sum, line.debit, 2), 0),
    totalCredit: lines.reduce((sum, line) => safeAdd(sum, line.credit, 2), 0),
  }
}

/**
 * Validates a template without touching the database — the caller surfaces the
 * message to the user, and the scheduler skips (never half-creates) bad rows.
 */
export function validateRecurringTemplate(type: string, template: RecurringTemplate): string | null {
  if (type === "journal") {
    const { lines, totalDebit, totalCredit } = recurringJournalLines(template)
    if (lines.length < 2) return "Jurnal berulang butuh minimal 2 baris (debit & kredit)"
    if (Math.abs(totalDebit - totalCredit) >= 0.005) {
      return `Jurnal berulang tidak balance: debit ${totalDebit} ≠ kredit ${totalCredit}`
    }
    return null
  }

  if (type === "expense") {
    if (!template.accountId) return "Akun beban wajib dipilih"
    if (!template.amount || template.amount <= 0) return "Nominal beban harus lebih dari 0"
    return null
  }

  return `Jenis transaksi berulang "${type}" tidak dikenal`
}

type RecurringDb = Pick<typeof prisma, "journal" | "expense" | "account"> &
  Partial<Pick<TxClient, "$queryRaw">>

/** Creates the scheduled document as a DRAFT and returns a human summary. */
async function generateDocument(
  schedule: { id: number; name: string; type: string },
  template: RecurringTemplate,
  date: Date,
  userId: number | null,
  db: RecurringDb = prisma,
): Promise<string> {
  if (schedule.type === "journal") {
    const { lines, totalDebit, totalCredit } = recurringJournalLines(template)
    await assertAccountsExist(db as TxClient, lines.map((line) => line.accountId), "Transaksi berulang")
    const { referenceType, referenceId } = recurringJournalReference(schedule.id, date)

    // Period key: a journal must never be born inside a closed accounting period.
    // The generated journal is DRAFT, but a DRAFT dated inside a locked period can
    // never be posted (`postJournal` re-checks the lock), so it would be a trap.
    // Failing here is loud and retryable: nextRunDate is only advanced after a
    // successful run, so the occurrence stays due until the period is reopened.
    // Cek lewat tx klaim bila ada: bacaan periodLockDate mengambil kunci
    // system_settings FOR UPDATE, jadi tutup-periode tak bisa menyelip di
    // antara cek ini dan journal.create (draft jebakan + jadwal sudah maju).
    await assertPeriodOpen(date, db.$queryRaw ? (db as TxClient) : undefined)

    // Idempotency: one schedule = one journal per document date. If the journal is
    // already there (e.g. the process died between the create and the schedule
    // advance) do NOT add a second one — skip creation and let the schedule advance,
    // otherwise the unique (referenceType, referenceId) pair would throw a cryptic
    // P2002 on every subsequent cron tick.
    const existing = await db.journal.findFirst({
      where: { referenceType, referenceId },
      select: { journalNumber: true },
    })
    if (existing) return `Jurnal ${existing.journalNumber} (sudah ada, dilewati)`

    const journalNumber = await generateDocumentNumber("JRN")

    const journal = await db.journal.create({
      data: {
        journalNumber,
        slug: await nextSlug("journal", journalNumber),
        transactionDate: date,
        referenceType,
        referenceId,
        description: template.description ?? `Transaksi berulang: ${schedule.name}`,
        type: "GENERAL",
        status: "DRAFT",
        totalDebit,
        totalCredit,
        createdBy: userId,
        entries: {
          create: lines.map((line) => ({
            accountId: line.accountId,
            debit: line.debit || 0,
            credit: line.credit || 0,
            memo: line.memo ?? template.description ?? null,
          })),
        },
      },
    })
    return `Jurnal ${journal.journalNumber}`
  }

  if (schedule.type === "expense") {
    await assertAccountsExist(db as TxClient, [template.accountId, template.paidFromAccountId], "Transaksi berulang")
    // Gated seperti jalur journal & createExpense biasa: draft tanggal tertutup
    // takkan bisa diproses onExpenseApproved (assertPeriodOpen lagi di hook),
    // jadi gagal keras di sini dan jadwal tetap due untuk retry. Sama seperti
    // cabang journal: cek lewat tx klaim agar terserialisasi terhadap
    // tutup-periode.
    await assertPeriodOpen(date, db.$queryRaw ? (db as TxClient) : undefined)

    const documentNo = await generateDocumentNumber("EXP")
    await db.expense.create({
      data: {
        documentNo,
        slug: await nextSlug("expense", documentNo),
        accountId: template.accountId!,
        paidFromAccountId: template.paidFromAccountId ?? null,
        categoryId: template.categoryId ?? null,
        vendorId: template.vendorId ?? null,
        amount: template.amount!,
        date,
        description: template.description ?? "Beban berulang",
        status: "draft",
        createdBy: userId,
      },
    })
    return `Beban ${documentNo}`
  }

  throw new Error(`Jenis transaksi berulang "${schedule.type}" tidak dikenal`)
}

/**
 * Runs every due template, creating DRAFT documents so a human still reviews
 * before anything hits stock or the general ledger. A failing template is
 * recorded and skipped rather than aborting the whole batch.
 */
export async function runDueRecurring(
  asOf: Date = new Date(),
  userId: number | null = null,
): Promise<{ processed: number; generated: string[]; errors: string[] }> {
  const due = await prisma.recurringTransaction.findMany({
    where: { isActive: true, deletedAt: null, nextRunDate: { lte: asOf } },
    orderBy: { nextRunDate: "asc" },
  })

  const generated: string[] = []
  const errors: string[] = []

  for (const schedule of due) {
    if (!isWithinSchedule(schedule.nextRunDate, schedule.startDate, schedule.endDate)) {
      // Past its end date → retire it instead of generating more documents.
      // Syarat isActive: jadwal yang sudah dinonaktifkan eksekusi lain tak
      // ditimpa lastResult-nya (count 0 = abaikan).
      await prisma.recurringTransaction.updateMany({
        where: { id: schedule.id, isActive: true },
        data: { isActive: false, lastResult: "Berakhir (melewati tanggal akhir)" },
      })
      continue
    }

    const template = parseRecurringTemplate(schedule.template)
    const invalid = validateRecurringTemplate(schedule.type, template)
    if (invalid) {
      errors.push(`${schedule.name}: ${invalid}`)
      // Syarat klaim sama dengan klaim utama: eksekusi lain yang sudah
      // memajukan nextRunDate tak boleh ditimpa lastResult-nya.
      await prisma.recurringTransaction.updateMany({
        where: { id: schedule.id, nextRunDate: schedule.nextRunDate },
        data: { lastResult: `Gagal: ${invalid}` },
      })
      continue
    }

    try {
      const runDate = schedule.nextRunDate
      const frequency = schedule.frequency
      if (!isRecurrenceFrequency(frequency)) throw new Error(`Frekuensi "${frequency}" tidak dikenal`)

      // Klaim atomik + dokumen dalam SATU tx (pola sama runRecurringNow):
      // klaim nextRunDate lama dulu; count 0 = eksekusi lain sudah menang,
      // lewati tanpa dokumen. Dokumen gagal = klaim ikut rollback.
      // Syarat isActive/deletedAt: scan due berjalan di luar tx, jadi hapus
      // atau nonaktifkan konkuren sesudah scan tidak memajukan nextRunDate
      // dan klaim {id, nextRunDate} saja tetap cocok — dokumen DRAFT akan
      // lahir untuk jadwal yang sudah mati. Mengikat status hidup ke klaim
      // membuat jadwal mati kalah klaim dan dilewati.
      const label = await prisma.$transaction(async (tx) => {
        const claimed = await tx.recurringTransaction.updateMany({
          where: { id: schedule.id, nextRunDate: runDate, isActive: true, deletedAt: null },
          data: {
            lastRunAt: asOf,
            runCount: { increment: 1 },
            // Advance past every missed occurrence, so a scheduler that was down
            // for months does not try to fire the whole backlog next run.
            nextRunDate: nextRunAfter(runDate, frequency as RecurrenceFrequency, schedule.interval, asOf),
          },
        })
        if (claimed.count === 0) return null

        const summary = await generateDocument(
          { id: schedule.id, name: schedule.name, type: schedule.type },
          template,
          runDate,
          userId ?? schedule.createdBy,
          tx,
        )
        await tx.recurringTransaction.update({
          where: { id: schedule.id },
          data: { lastResult: summary },
        })
        return summary
      })
      if (label === null) continue
      generated.push(`${schedule.name} → ${label}`)
    } catch (error) {
      const message = error instanceof Error ? error.message : "Gagal membuat dokumen"
      errors.push(`${schedule.name}: ${message}`)
      // runDate = nextRunDate yang dibaca due-scan loop ini; tx klaim yang
      // gagal sudah rollback sehingga nilai DB masih runDate. Bila eksekusi
      // lain sudah memajukannya (count 0), lastResult pemenang tak ditimpa.
      await prisma.recurringTransaction.updateMany({
        where: { id: schedule.id, nextRunDate: schedule.nextRunDate },
        data: { lastResult: `Gagal: ${message}` },
      })
    }
  }

  return { processed: due.length, generated, errors }
}

